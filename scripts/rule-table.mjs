// Render the validation rule registry as a Markdown table.
//
// Usage: node scripts/rule-table.mjs [--check]
// Writes <specification>/validation/rules.md from validation/rules/*.yaml, or
// with --check exits non-zero when the file is missing or stale.

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { candidateSpecification } from './candidate-specification.mjs';
import { decodeDocumentSource } from './decode-document.mjs';

const revisions = ['2024-11-05', '2025-03-26', '2025-06-18', '2025-11-25', '2026-07-28'];

function cell(text) {
  return String(text ?? '').replace(/\s+/g, ' ').trim().replaceAll('|', '\\|');
}

function applicabilityCell(applicability) {
  if (!applicability) return 'all';
  const byValue = new Map();
  for (const revision of revisions) {
    const value = applicability[revision];
    byValue.set(value, [...(byValue.get(value) ?? []), revision]);
  }
  if (byValue.size === 1 && byValue.has('applies')) return 'all';
  return [...byValue]
    .filter(([value]) => value !== 'not-applicable')
    .map(([value, list]) => `${value}: ${list.join(', ')}`)
    .join('; ');
}

function notesCell(rule) {
  const notes = [];
  for (const arbitration of rule.arbitrations ?? []) {
    notes.push(`Arbitration (${arbitration.status}): ${arbitration.behavior}`);
  }
  for (const gap of rule.gaps ?? []) {
    notes.push(`Gap (${gap.resolution}): ${gap.behavior}`);
  }
  return notes.map(cell).join('<br>');
}

export function renderRuleTable(rulesDirectory) {
  const files = fs.readdirSync(rulesDirectory).filter((name) => /\.ya?ml$/.test(name)).sort();
  const rules = files.flatMap((file) => decodeDocumentSource(
    fs.readFileSync(path.join(rulesDirectory, file), 'utf8'),
    'yaml',
    file
  ).rules.map((rule) => ({ ...rule, file })));
  rules.sort((left, right) => left.id.localeCompare(right.id));

  const lines = [
    '# Validation Rules',
    '',
    '<!-- Generated by scripts/rule-table.mjs from rules/*.yaml; do not edit by hand. -->',
    '',
    'Each rule has a permanent identifier. The specification text cites rules as',
    '(rule `<id>`), and every validator diagnostic carries the identifier of the',
    'rule it reports in its `rule` property. Field meanings are defined in',
    '[README.md](README.md#rule-records); the full records, including sources and',
    'fixtures, are in [`rules/`](rules/).',
    '',
    `${rules.length} rules.`,
    '',
    '| Rule | Summary | Owner | Requirement | Revisions | Diagnostics | Status | Arbitrations and gaps |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |'
  ];
  for (const rule of rules) {
    const diagnostics = rule.diagnostics.map(({ code, severity }) => `\`${code}\` (${severity})`).join('<br>');
    lines.push(`| <a id="${rule.id}"></a>[\`${rule.id}\`](rules/${rule.file}) | ${cell(rule.summary)} | ${rule.owner} | ${rule.requirement ?? ''} | ${cell(applicabilityCell(rule.applicability))} | ${diagnostics || 'none'} | ${rule.status} | ${notesCell(rule)} |`);
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  const { specificationRoot } = candidateSpecification(root);
  const validationRoot = path.join(root, specificationRoot, 'validation');
  const target = path.join(validationRoot, 'rules.md');
  const rendered = renderRuleTable(path.join(validationRoot, 'rules'));
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== rendered) {
      console.error(`${path.relative(root, target)} is stale; run npm run rules:table`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, rendered);
    console.log(`Wrote ${path.relative(root, target)}.`);
  }
}
